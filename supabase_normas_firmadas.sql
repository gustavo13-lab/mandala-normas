create table if not exists public.normas_firmadas (
 id bigint generated by default as identity primary key,
 nombre text not null, dni_nie text not null, whatsapp text,
 restaurante text not null, puesto text not null, version text not null,
 firmado_en timestamptz not null, firma_png text not null,
 documento_html text,
 aceptado boolean not null default true, created_at timestamptz not null default now()
);
alter table public.normas_firmadas add column if not exists whatsapp text;
alter table public.normas_firmadas enable row level security;
drop policy if exists "insert_normas_firmadas" on public.normas_firmadas;
drop policy if exists "read_normas_firmadas" on public.normas_firmadas;
create policy "insert_normas_firmadas" on public.normas_firmadas for insert to anon with check (true);
create policy "read_normas_firmadas" on public.normas_firmadas for select to anon using (true);

drop policy if exists "delete_normas_firmadas" on public.normas_firmadas;
create policy "delete_normas_firmadas" on public.normas_firmadas for delete to anon using (true);

alter table public.normas_firmadas add column if not exists documento_html text;
